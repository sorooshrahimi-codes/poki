"""Cut the hatted fisher sheets into one sprite per hat and pose, measure each sprite's hull and rod
tip, and write src/data/kidgeo.ts so every sprite lines up on the same hull in the game.
Usage: python3 -I fisher.py RAW_DIR"""
import importlib.util, os, shutil, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "..", "public", "art")
spec = importlib.util.spec_from_file_location("proc", os.path.join(HERE, "process.py"))
proc = importlib.util.module_from_spec(spec); spec.loader.exec_module(proc)

HATS = ["beanie", "rain", "sailor", "frog", "straw", "pirate", "crown"]
POSES = ["idle", "cast", "reel", "cheer"]  # sheet order: top-left, top-right, bottom-left, bottom-right


def measure(path, pose):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    a = im.getchannel("A")
    hull = a.crop((0, int(h * 0.72), w, h)).point(lambda v: 255 if v > 60 else 0).getbbox()
    px = im.load()
    best = None
    for y in range(int(h * 0.32)):
        for x in range(w):
            if px[x, y][3] > 80:
                key = x if pose == "cast" else -x
                if best is None or key < best[0]:
                    best = (key, x, y)
    return [round(hull[0] / w, 3), round(hull[2] / w, 3)], [round(best[1] / w, 3), round(best[2] / h, 3)]


def main(raw):
    geo = {}
    for hat in HATS:
        sheet = Image.open(os.path.join(raw, f"kidhat_{hat}.png")).convert("RGBA")
        w, h = sheet.size
        for i, pose in enumerate(POSES):
            x, y = (i % 2) * w // 2, (i // 2) * h // 2
            name = f"kid_{hat}_{pose}"
            proc.save(proc.trim(sheet.crop((x, y, x + w // 2, y + h // 2))), name)
    # the original red-cap art is the default "cap" look
    for pose in POSES:
        src = "boat" if pose == "idle" else f"boat_{pose}"
        shutil.copy(os.path.join(ART, src + ".webp"), os.path.join(ART, f"kid_cap_{pose}.webp"))
    for hat in ["cap"] + HATS:
        for pose in POSES:
            name = f"kid_{hat}_{pose}"
            hull, tip = measure(os.path.join(ART, name + ".webp"), pose)
            geo[name] = {"hull": hull, "tip": tip}
            print(name, hull, tip)
    out = os.path.join(HERE, "..", "..", "src", "data", "kidgeo.ts")
    with open(out, "w") as f:
        f.write("// Generated by tools/art/fisher.py: hull extent and rod tip of each fisher sprite (fractions).\n")
        f.write("export const KID_GEO: Record<string, { hull: [number, number]; tip: [number, number] }> = {\n")
        for k, v in geo.items():
            f.write(f'  "{k}": {{ hull: [{v["hull"][0]}, {v["hull"][1]}], tip: [{v["tip"][0]}, {v["tip"][1]}] }},\n')
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1])
