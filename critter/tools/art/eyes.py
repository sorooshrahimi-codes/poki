"""Find the eyes of chibi critters (a big dark round iris with a white shine on it) so they can blink.
Writes src/data/eyes.ts: per sprite up to 2 ellipses [cx, cy, rx, ry] as fractions, plus the eyelid colour.
Usage: python3 -I eyes.py"""
import json, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "..", "public", "art")
OUT = os.path.join(HERE, "..", "..", "src", "data", "eyes.ts")
SKIP = ("bg_", "kid_", "pedestal", "jar", "coin", "nozzle")


def components(mask):
    h, w = mask.shape
    seen = np.zeros_like(mask, dtype=bool)
    out = []
    for y0, x0 in zip(*np.nonzero(mask)):
        if seen[y0, x0]: continue
        st = [(y0, x0)]; seen[y0, x0] = True; py, px = [], []
        while st:
            y, x = st.pop(); py.append(y); px.append(x)
            for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
                if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:
                    seen[ny, nx] = True; st.append((ny, nx))
        out.append((np.array(py), np.array(px)))
    return out


def find(path):
    im = Image.open(path).convert("RGBA")
    k = 200 / max(im.size)
    im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    a = np.asarray(im).astype(int)
    H, W = a.shape[:2]
    lum = 0.3 * a[..., 0] + 0.59 * a[..., 1] + 0.11 * a[..., 2]
    sat = a[..., :3].max(-1) - a[..., :3].min(-1)
    al = a[..., 3] > 200
    white = (lum > 215) & (sat < 50) & al
    # iris: dark, or a saturated mid-dark colour (amber, brown, purple eyes); excludes the navy outline only partly,
    # so the shape test below does the rest
    iris = al & ((lum < 70) | ((lum < 150) & (sat > 60)))
    cands = []
    for ys, xs in components(iris):
        n = len(ys)
        x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
        bw, bh = x1 - x0 + 1, y1 - y0 + 1
        if n < 25 or bw > W * 0.32 or bh > H * 0.36 or bw < 5 or bh < 5: continue
        if bw / bh > 1.8 or bh / bw > 1.8: continue
        fill = n / (bw * bh)
        if fill < 0.45: continue  # outlines and thin strokes are not eyes
        cy, cx = (y0 + y1) / 2 / H, (x0 + x1) / 2 / W
        if not (0.12 < cy < 0.72 and 0.1 < cx < 0.9): continue
        # an eye has a shine: white pixels inside its box
        shine = white[y0:y1 + 1, x0:x1 + 1].sum()
        if shine < 2: continue
        cands.append((n, x0, y0, x1, y1))
    cands.sort(reverse=True)
    eyes = []
    for c in cands:
        if not eyes: eyes.append(c); continue
        e = eyes[0]
        same_row = abs((c[2] + c[4]) / 2 - (e[2] + e[4]) / 2) < (e[4] - e[2]) * 0.7
        similar = c[0] > e[0] * 0.35
        apart = c[1] > e[3] or c[3] < e[1]
        if same_row and similar and apart: eyes.append(c); break
    res = []
    for _, x0, y0, x1, y1 in eyes:
        # lid colour: the body just below the eye
        patch = a[min(H - 1, y1 + 2):min(H, y1 + 6), x0:x1 + 1].reshape(-1, 4)
        patch = patch[(patch[:, 3] > 200)]
        lp = 0.3 * patch[:, 0] + 0.59 * patch[:, 1] + 0.11 * patch[:, 2] if len(patch) else np.array([])
        patch = patch[lp > 80] if len(patch) else patch
        col = np.median(patch[:, :3], axis=0).astype(int) if len(patch) else np.array([200, 170, 150])
        g = 1.12
        res.append([round((x0 + x1) / 2 / W, 4), round((y0 + y1) / 2 / H, 4), round((x1 - x0) / 2 / W * g, 4), round((y1 - y0) / 2 / H * g, 4), "#%02x%02x%02x" % tuple(col)])
    return res


def main():
    out = {}
    for f in sorted(os.listdir(ART)):
        n = f[:-5]
        if not f.endswith(".webp") or n.startswith(SKIP): continue
        e = find(os.path.join(ART, f))
        if len(e) == 2: out[n] = e  # only blink with both eyes found: one eye alone would wink
        print(f"{n:14s} {len(e)}")
    with open(OUT, "w") as fh:
        fh.write("// Generated by tools/art/eyes.py: [cx, cy, rx, ry] fractions of the sprite, then the eyelid colour.\n")
        fh.write("export type Eye = [number, number, number, number, string];\n")
        fh.write("export const EYES: Record<string, Eye[]> = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("sprites with eyes:", len(out))


if __name__ == "__main__":
    main()
